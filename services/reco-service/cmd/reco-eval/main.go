// Command reco-eval runs the offline evaluation (synthetic users, time-split
// holdout, P/R/NDCG@K, coverage, diversity, novelty, cold start, closed-loop
// sessions) comparing the old heuristic with the reco blend and ablations.
//
//	go run ./cmd/reco-eval [-users 300 -tracks 720 -seed 7] [-out ../../docs/reco/evaluation-results.md]
package main

import (
	"flag"
	"fmt"
	"os"
	"time"

	"github.com/tapenest/tapenest/services/reco-service/internal/eval"
)

func main() {
	cfg := eval.DefaultConfig()
	flag.IntVar(&cfg.Users, "users", cfg.Users, "synthetic users")
	flag.IntVar(&cfg.Tracks, "tracks", cfg.Tracks, "synthetic tracks")
	flag.IntVar(&cfg.EventsPerUser, "events", cfg.EventsPerUser, "events per user")
	seed := flag.Uint64("seed", cfg.Seed, "random seed")
	out := flag.String("out", "", "write the markdown report to this file")
	seeds := flag.Int("seeds", 5, "average over this many synthetic worlds")
	tune := flag.Int("tune", 0, "random-search N weight settings on a validation world (seed+1000) and print the best")
	flag.Parse()
	cfg.Seed = *seed
	if *tune > 0 {
		vcfg := cfg
		vcfg.Seed = cfg.Seed + 1000
		fmt.Print(eval.TuneMarkdown(eval.Tune(vcfg, *tune, cfg.Seed), 8))
		return
	}
	start := time.Now()
	rep := eval.RunSeeds(cfg, *seeds, eval.Suite())
	md := rep.Markdown()
	fmt.Print(md)
	fmt.Fprintf(os.Stderr, "evaluation took %s\n", time.Since(start).Round(time.Millisecond))
	if *out != "" {
		if err := os.WriteFile(*out, []byte("<!-- generated by services/reco-service/cmd/reco-eval; do not edit -->\n\n"+md), 0o644); err != nil { //nolint:gosec // public report committed to docs/
			fmt.Fprintln(os.Stderr, "write:", err)
			os.Exit(1)
		}
	}
}
